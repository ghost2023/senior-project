import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { IconSparkles } from "@tabler/icons-react";
import { getSession } from "@/lib/permissions";
import { getLatestRiskAssessment, getStudentByUserId } from "@/lib/queries/student";

interface ContributingFactor {
  feature: string;
  shapValue: number;
  direction: "increases_risk" | "decreases_risk";
}

export default async function StudentPredictionsPage() {
  const session = await getSession();
  const student = await getStudentByUserId(session!.user.id);
  if (!student) return <div>No student profile found.</div>;

  const risk = await getLatestRiskAssessment(student.id);

  if (!risk) {
    return (
      <div className="flex flex-col gap-8">
        <h2 className="text-3xl font-bold tracking-tight">AI Predictive Engine</h2>
        <Card className="h-[40vh] flex items-center justify-center border-2 border-dashed bg-accent/5 shadow-none">
          <div className="text-center max-w-sm">
            <IconSparkles className="mx-auto mb-3 text-muted-foreground" size={28} />
            <p className="text-sm font-bold">No prediction available yet</p>
            <p className="text-xs text-muted-foreground mt-1">
              Predictions are generated by the risk model after it has been trained and run at least once.
            </p>
          </div>
        </Card>
      </div>
    );
  }

  const factors = (risk.contributingFactors as ContributingFactor[]) ?? [];

  return (
    <div className="flex flex-col gap-8">
      <h2 className="text-3xl font-bold tracking-tight">AI Predictive Engine</h2>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        <Card className="bg-primary text-primary-foreground border-none">
          <CardHeader>
            <CardDescription className="text-primary-foreground/60 text-xs font-bold uppercase tracking-widest">
              Predicted Final GPA
            </CardDescription>
            <CardTitle className="text-5xl font-bold font-mono">
              {risk.predictedFinalGrade ? Number(risk.predictedFinalGrade).toFixed(2) : "—"}
            </CardTitle>
          </CardHeader>
        </Card>
        <Card>
          <CardHeader>
            <CardDescription className="text-xs font-bold uppercase tracking-widest">Risk Level</CardDescription>
            <CardTitle className="text-3xl font-bold capitalize">{risk.riskLevel.replace("_", " ")}</CardTitle>
          </CardHeader>
        </Card>
        <Card>
          <CardHeader>
            <CardDescription className="text-xs font-bold uppercase tracking-widest">Confidence</CardDescription>
            <CardTitle className="text-3xl font-bold font-mono">
              {Math.round(Number(risk.confidenceScore) * 100)}%
            </CardTitle>
          </CardHeader>
        </Card>
      </div>

      <Card>
        <CardHeader className="border-b">
          <CardTitle>Contributing Factors</CardTitle>
          <CardDescription>What drove this prediction, in order of influence (rule #20, USA-04)</CardDescription>
        </CardHeader>
        <CardContent className="flex flex-col gap-3 pt-6">
          {factors.length === 0 && <p className="text-xs text-muted-foreground">No factor breakdown available.</p>}
          {factors.map((f, i) => (
            <div key={i} className="flex items-center justify-between gap-4">
              <span className="text-sm font-medium">{f.feature}</span>
              <Badge variant={f.direction === "increases_risk" ? "destructive" : "secondary"}>
                {f.direction === "increases_risk" ? "Increases risk" : "Decreases risk"}
              </Badge>
            </div>
          ))}
        </CardContent>
      </Card>

      <p className="text-[10px] text-muted-foreground uppercase tracking-widest font-mono">
        Model: {risk.model?.modelType} v{risk.model?.version} — generated{" "}
        {new Date(risk.generatedAt).toLocaleString()}
      </p>
    </div>
  );
}
